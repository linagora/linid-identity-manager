package io.github.linagora.linid.im.sync.persistence.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.OffsetDateTime;
import java.util.List;
import java.util.UUID;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

/**
 * Entity mapped to the {@code computed_rights} table of the linid-api database: the rights computed for an account and
 * application pair, with the checksums used by the computation and the {@code sync-api} run that wrote them.
 *
 * <p>The identifier is generated by Hibernate, so that the inserts can be grouped. The dates are set by the database,
 * and are not read again after an insert or an update, so that the updates can be grouped too.</p>
 *
 * <p>No version: only {@code sync-api} writes this table.</p>
 */
@Entity
@Table(name = "computed_rights")
@Data
@NoArgsConstructor
public class ComputedRight {

    /**
     * Identifier of the computed rights.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "cpr_id")
    private UUID cprId;

    /**
     * Identifier of the account of the pair.
     */
    @Column(name = "act_id")
    private UUID actId;

    /**
     * Identifier of the application of the pair.
     */
    @Column(name = "app_id")
    private UUID appId;

    /**
     * Allow returned by OPA for the account on the application.
     */
    @Column(name = "allow")
    private boolean allow;

    /**
     * Roles returned by OPA for the account on the application.
     */
    @Column(name = "roles", columnDefinition = "jsonb")
    @JdbcTypeCode(SqlTypes.JSON)
    private List<String> roles;

    /**
     * Claims rendered from the claims template of the application, as a JSON object.
     */
    @Column(name = "claims", columnDefinition = "jsonb")
    @JdbcTypeCode(SqlTypes.JSON)
    private String claims;

    /**
     * Checksum of the account payload used by the computation.
     */
    @Column(name = "payload_checksum")
    private String payloadChecksum;

    /**
     * Checksum of the application script used by the computation.
     */
    @Column(name = "script_checksum")
    private String scriptChecksum;

    /**
     * Checksum of the application claims template used by the computation.
     */
    @Column(name = "claims_template_checksum")
    private String claimsTemplateChecksum;

    /**
     * Identifier of the {@code sync-api} instance that wrote the rights.
     */
    @Column(name = "sync_instance_id")
    private String syncInstanceId;

    /**
     * Identifier of the Spring Batch job execution that wrote the rights.
     */
    @Column(name = "sync_job_execution_id")
    private Long syncJobExecutionId;

    /**
     * Identifier of the account that created the row, the technical account of {@code sync-api}.
     */
    @Column(name = "created_by")
    private UUID createdBy;

    /**
     * Identifier of the account that last updated the row, the technical account of {@code sync-api}.
     */
    @Column(name = "updated_by")
    private UUID updatedBy;

    /**
     * Date of creation of the row, set by the database.
     */
    @Column(name = "insert_date", insertable = false, updatable = false)
    private OffsetDateTime insertDate;

    /**
     * Date of the last update of the row, set by the database.
     */
    @Column(name = "update_date", insertable = false, updatable = false)
    private OffsetDateTime updateDate;
}
