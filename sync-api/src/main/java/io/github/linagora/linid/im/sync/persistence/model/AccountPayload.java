package io.github.linagora.linid.im.sync.persistence.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.OffsetDateTime;
import java.util.Map;
import java.util.UUID;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

/**
 * Entity mapped to the {@code account_payloads} table of the linid-api database: the payload of an account, used as
 * OPA input, with its checksum and the {@code sync-api} run that wrote it.
 *
 * <p>The identifier is generated by Hibernate, so that the inserts can be grouped. The dates are set by the database,
 * and are not read again after an insert or an update, so that the updates can be grouped too.</p>
 *
 * <p>No version: only {@code sync-api} writes this table.</p>
 */
@Entity
@Table(name = "account_payloads")
@Data
@NoArgsConstructor
public class AccountPayload {

    /**
     * Identifier of the payload.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "acp_id")
    private UUID acpId;

    /**
     * Identifier of the account the payload belongs to.
     */
    @Column(name = "act_id")
    private UUID actId;

    /**
     * Payload of the account, used as OPA input.
     */
    @Column(name = "payload", columnDefinition = "jsonb")
    @JdbcTypeCode(SqlTypes.JSON)
    private Map<String, Object> payload;

    /**
     * Checksum of the payload, computed on its compact JSON with sorted keys.
     */
    @Column(name = "checksum")
    private String checksum;

    /**
     * Identifier of the {@code sync-api} instance that wrote the payload.
     */
    @Column(name = "sync_instance_id")
    private String syncInstanceId;

    /**
     * Identifier of the Spring Batch job execution that wrote the payload.
     */
    @Column(name = "sync_job_execution_id")
    private Long syncJobExecutionId;

    /**
     * Identifier of the account that created the row, the technical account of {@code sync-api}.
     */
    @Column(name = "created_by")
    private UUID createdBy;

    /**
     * Identifier of the account that last updated the row, the technical account of {@code sync-api}.
     */
    @Column(name = "updated_by")
    private UUID updatedBy;

    /**
     * Date of creation of the row, set by the database.
     */
    @Column(name = "insert_date", insertable = false, updatable = false)
    private OffsetDateTime insertDate;

    /**
     * Date of the last update of the row, set by the database.
     */
    @Column(name = "update_date", insertable = false, updatable = false)
    private OffsetDateTime updateDate;
}
