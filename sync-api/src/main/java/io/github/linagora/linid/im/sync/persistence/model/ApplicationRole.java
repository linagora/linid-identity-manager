package io.github.linagora.linid.im.sync.persistence.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.util.UUID;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.Immutable;

/**
 * Read-only entity mapped to the {@code application_roles} table of the linid-api database, limited to the columns
 * read by {@code sync-api}: the roles of an application, against which the roles returned by OPA are checked.
 *
 * <p>This entity is immutable and intended strictly for read operations.</p>
 */
@Entity
@Immutable
@Table(name = "application_roles")
@Data
@NoArgsConstructor
@AllArgsConstructor
public class ApplicationRole {

    /**
     * Identifier of the role.
     */
    @Id
    @Column(name = "aro_id")
    private UUID aroId;

    /**
     * Identifier of the application the role belongs to.
     */
    @Column(name = "app_id")
    private UUID appId;

    /**
     * Name of the role, unique within the application.
     */
    @Column(name = "name")
    private String name;
}
